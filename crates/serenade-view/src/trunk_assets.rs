//! Reader for Trunk's versioned `trunk-assets.json` output.

use std::{
    collections::{BTreeMap, BTreeSet},
    ffi::OsString,
    path::{Component, Path, PathBuf},
};

use base64::{Engine as _, engine::general_purpose::STANDARD};
use serde::Deserialize;
use sha2::{Digest, Sha256, Sha384, Sha512};

use crate::ViewError;

const MIN_SUPPORTED_MANIFEST_VERSION: u32 = 1;
const CURRENT_MANIFEST_VERSION: u32 = 2;

/// Filename emitted by Trunk for its build asset manifest.
pub const TRUNK_ASSET_MANIFEST_FILE: &str = "trunk-assets.json";

/// Environment variable set by Serenade mode commands with the manifest path.
pub const TRUNK_ASSET_MANIFEST_ENV: &str = "SERENADE_TRUNK_ASSET_MANIFEST";

/// Environment variable set by `serenade-universal` with the frontend output directory.
pub const TRUNK_DIST_DIRECTORY_ENV: &str = "SERENADE_TRUNK_DIST_DIR";

/// Assets produced by Trunk for one frontend build.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq)]
pub struct TrunkAssetManifest {
    /// Schema version.
    pub version: u32,
    /// Configured public URL prefix.
    pub public_url: String,
    /// Finalized HTML output filename.
    pub html: String,
    /// External assets in source HTML order.
    pub assets: Vec<TrunkAssetReference>,
    /// Rust/WASM bundles; empty when the application has no Rust frontend.
    pub wasm: Vec<TrunkWasmBundle>,
}

/// One external asset emitted by Trunk.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq)]
pub struct TrunkAssetReference {
    /// Source HTML order.
    pub order: usize,
    /// Asset role (`stylesheet`, `script`, or `icon`).
    pub role: String,
    /// Exact public URL.
    pub url: String,
    /// SHA-256 digest emitted by manifest schema v2.
    pub content_digest: Option<String>,
    /// Attributes emitted for this asset, excluding its URL attribute.
    pub attributes: BTreeMap<String, String>,
}

/// Rust/WASM runtime bundle and initialization information.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq)]
pub struct TrunkWasmBundle {
    /// `main` or `worker`.
    pub app_type: String,
    /// Source HTML order, absent for Trunk's implicit Cargo application.
    pub order: Option<usize>,
    /// Exact wasm-bindgen JavaScript module URL.
    pub js_url: String,
    /// SHA-256 digest emitted by manifest schema v2.
    pub js_content_digest: Option<String>,
    /// Exact WebAssembly module URL.
    pub wasm_url: String,
    /// SHA-256 digest emitted by manifest schema v2.
    pub wasm_content_digest: Option<String>,
    /// WebAssembly module size in bytes.
    pub wasm_size: u64,
    /// Optional custom initializer module URL.
    pub initializer_url: Option<String>,
    /// SHA-256 digest emitted for an initializer by manifest schema v2.
    pub initializer_content_digest: Option<String>,
    /// Whether the wasm-bindgen initializer expects a `module_or_path` object.
    pub init_with_object: bool,
    /// Whether Rust exports are imported into the initializer.
    pub import_bindings: bool,
    /// Optional global variable name for imported bindings.
    pub import_bindings_name: Option<String>,
    /// Optional decompression algorithm.
    pub compression_algorithm: Option<String>,
    /// Cross-origin mode used for loading resources.
    pub cross_origin: String,
    /// Whether Trunk injects the initializer into its HTML.
    pub inject_scripts: bool,
    /// Optional Trunk initializer template.
    pub custom_script_pattern: Option<String>,
    /// Optional Trunk preload template.
    pub custom_preload_pattern: Option<String>,
    /// Parameters available to Trunk's custom templates.
    pub pattern_parameters: BTreeMap<String, String>,
    /// Preload references generated by Trunk's SRI pipeline.
    pub preloads: Vec<TrunkPreloadReference>,
}

/// One preload generated for a Rust/WASM bundle.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq)]
pub struct TrunkPreloadReference {
    /// `preload` or `modulepreload`.
    pub rel: String,
    /// Exact public URL.
    pub url: String,
    /// SHA-256 digest emitted by manifest schema v2.
    pub content_digest: Option<String>,
    /// `crossorigin` attribute value.
    pub cross_origin: String,
    /// SRI value when enabled.
    pub integrity: Option<String>,
    /// Optional preload `as` attribute.
    #[serde(rename = "as")]
    pub as_type: Option<String>,
    /// Optional preload `type` attribute.
    #[serde(rename = "type")]
    pub media_type: Option<String>,
}

impl TrunkAssetManifest {
    /// Reads the manifest path supplied by a Serenade mode command.
    ///
    /// Call once during application startup, not once per request.
    ///
    /// # Errors
    ///
    /// Returns an error when the environment variable is missing or the
    /// manifest is missing, malformed, or incompatible.
    pub fn read_from_env() -> Result<Self, ViewError> {
        Self::read_from_environment(std::env::var_os(TRUNK_ASSET_MANIFEST_ENV))
    }

    fn read_from_environment(path: Option<OsString>) -> Result<Self, ViewError> {
        let path = path.ok_or_else(|| {
            ViewError::msg(format!(
                "environment variable {TRUNK_ASSET_MANIFEST_ENV} is not set"
            ))
        })?;
        Self::read(path)
    }

    /// Reads and validates the manifest once, suitable for build/startup use.
    ///
    /// # Errors
    ///
    /// Returns an error when the file is missing, malformed, incompatible, or
    /// contains invalid asset references.
    pub fn read(path: impl AsRef<Path>) -> Result<Self, ViewError> {
        let path = path.as_ref();
        let contents = std::fs::read(path).map_err(|error| {
            ViewError::msg(format!("failed to read {}: {error}", path.display()))
        })?;
        let manifest: Self = serde_json::from_slice(&contents)
            .map_err(|error| ViewError::msg(format!("invalid Trunk asset manifest: {error}")))?;
        manifest.validate()?;
        Ok(manifest)
    }

    /// Parses and validates Trunk manifest JSON bytes.
    ///
    /// # Errors
    ///
    /// Returns an error for malformed or incompatible manifests.
    pub fn from_json(contents: &[u8]) -> Result<Self, ViewError> {
        let manifest: Self = serde_json::from_slice(contents)
            .map_err(|error| ViewError::msg(format!("invalid Trunk asset manifest: {error}")))?;
        manifest.validate()?;
        Ok(manifest)
    }

    fn validate(&self) -> Result<(), ViewError> {
        if !(MIN_SUPPORTED_MANIFEST_VERSION..=CURRENT_MANIFEST_VERSION).contains(&self.version) {
            return Err(ViewError::msg(format!(
                "unsupported Trunk asset manifest version {}; supported versions are {} through {}",
                self.version, MIN_SUPPORTED_MANIFEST_VERSION, CURRENT_MANIFEST_VERSION
            )));
        }
        if self.public_url.trim().is_empty() {
            return Err(ViewError::msg(
                "Trunk asset manifest has an empty public URL prefix",
            ));
        }
        validate_public_url(&self.public_url)?;
        if self.html.trim().is_empty() {
            return Err(ViewError::msg(
                "Trunk asset manifest has an empty HTML output filename",
            ));
        }

        let mut previous_order = None;
        for asset in &self.assets {
            if !matches!(asset.role.as_str(), "stylesheet" | "script" | "icon") {
                return Err(ViewError::msg(format!(
                    "unsupported Trunk asset role `{}`",
                    asset.role
                )));
            }
            if asset.url.trim().is_empty() {
                return Err(ViewError::msg(format!(
                    "Trunk {} asset at order {} has an empty URL",
                    asset.role, asset.order
                )));
            }
            if self.version >= 2 && asset.content_digest.is_none() {
                return Err(ViewError::msg(format!(
                    "Trunk {} asset `{}` is missing its version 2 content digest",
                    asset.role, asset.url
                )));
            }
            if previous_order.is_some_and(|order| asset.order <= order) {
                return Err(ViewError::msg(
                    "Trunk asset manifest entries are not in strictly increasing source order",
                ));
            }
            previous_order = Some(asset.order);
        }

        let mut wasm_orders = BTreeSet::new();
        for bundle in &self.wasm {
            if !matches!(bundle.app_type.as_str(), "main" | "worker") {
                return Err(ViewError::msg(format!(
                    "unsupported Trunk WASM application type `{}`",
                    bundle.app_type
                )));
            }
            if bundle.js_url.trim().is_empty() || bundle.wasm_url.trim().is_empty() {
                return Err(ViewError::msg(
                    "Trunk WASM bundle has an empty JavaScript or WebAssembly URL",
                ));
            }
            if self.version >= 2
                && (bundle.js_content_digest.is_none()
                    || bundle.wasm_content_digest.is_none()
                    || bundle.initializer_url.is_some()
                        != bundle.initializer_content_digest.is_some())
            {
                return Err(ViewError::msg(
                    "Trunk WASM bundle is missing a version 2 content digest",
                ));
            }
            if bundle.order.is_some_and(|order| !wasm_orders.insert(order)) {
                return Err(ViewError::msg(
                    "Trunk WASM bundles have duplicate source order values",
                ));
            }
            for preload in &bundle.preloads {
                if !matches!(preload.rel.as_str(), "preload" | "modulepreload")
                    || preload.url.trim().is_empty()
                {
                    return Err(ViewError::msg(
                        "Trunk WASM bundle contains an invalid preload reference",
                    ));
                }
                if self.version >= 2 && preload.content_digest.is_none() {
                    return Err(ViewError::msg(format!(
                        "Trunk preload `{}` is missing its version 2 content digest",
                        preload.url
                    )));
                }
            }
        }
        self.validate_url_prefixes()
    }

    /// Requires every referenced URL to sit under `public_url`, so parsed manifests
    /// never carry another scheme or origin even before output validation.
    fn validate_url_prefixes(&self) -> Result<(), ViewError> {
        let urls = self
            .assets
            .iter()
            .map(|asset| &asset.url)
            .chain(self.wasm.iter().flat_map(|bundle| {
                [&bundle.js_url, &bundle.wasm_url]
                    .into_iter()
                    .chain(&bundle.initializer_url)
                    .chain(bundle.preloads.iter().map(|preload| &preload.url))
            }));
        for url in urls {
            self.local_asset_path(url)?;
        }
        Ok(())
    }

    /// Validates that every local output referenced by the manifest exists and
    /// matches its declared size and enabled SRI digests.
    ///
    /// # Errors
    ///
    /// Returns an error when a reference escapes the output directory, an
    /// artifact is missing or stale, or an integrity digest does not match.
    pub fn validate_output(&self, dist: impl AsRef<Path>) -> Result<(), ViewError> {
        let root = canonical_output_root(dist.as_ref())?;
        let html_path = safe_relative_path(&self.html)?;
        contained_file(&root, &html_path, "HTML output")?;

        for asset in &self.assets {
            let path = self.local_asset_path(&asset.url)?;
            let (file, _) = contained_file(
                &root,
                &path,
                &format!("{} asset `{}`", asset.role, asset.url),
            )?;
            if let Some(content_digest) = &asset.content_digest {
                verify_digest(&file, content_digest)?;
            }
            if let Some(integrity) = asset.attributes.get("integrity") {
                verify_digest(&file, integrity)?;
            }
        }

        for bundle in &self.wasm {
            let js_path = self.local_asset_path(&bundle.js_url)?;
            let (js_file, _) = contained_file(&root, &js_path, "WASM JavaScript loader")?;
            if let Some(content_digest) = &bundle.js_content_digest {
                verify_digest(&js_file, content_digest)?;
            }
            let wasm_path = self.local_asset_path(&bundle.wasm_url)?;
            let (wasm_file, wasm_metadata) =
                contained_file(&root, &wasm_path, "WebAssembly module")?;
            if let Some(content_digest) = &bundle.wasm_content_digest {
                verify_digest(&wasm_file, content_digest)?;
            }
            let actual_size = wasm_metadata.len();
            if actual_size != bundle.wasm_size {
                return Err(ViewError::msg(format!(
                    "stale WebAssembly module `{}`: manifest size is {} bytes, file size is {actual_size} bytes",
                    bundle.wasm_url, bundle.wasm_size
                )));
            }
            if let Some(initializer_url) = &bundle.initializer_url {
                let path = self.local_asset_path(initializer_url)?;
                let (file, _) = contained_file(&root, &path, "WASM initializer")?;
                if let Some(content_digest) = &bundle.initializer_content_digest {
                    verify_digest(&file, content_digest)?;
                }
            }
            for preload in &bundle.preloads {
                let path = self.local_asset_path(&preload.url)?;
                let (file, _) = contained_file(&root, &path, "WASM preload")?;
                if let Some(content_digest) = &preload.content_digest {
                    verify_digest(&file, content_digest)?;
                }
                if let Some(integrity) = &preload.integrity {
                    verify_digest(&file, integrity)?;
                }
            }
        }

        Ok(())
    }

    /// Resolves a public URL or request path to the real file it names inside
    /// the Trunk output directory, for servers that host the output themselves.
    ///
    /// Applies [`Self::output_path_for_url`], then follows symbolic links and
    /// rejects any file whose real location is outside `dist`, including files
    /// that the manifest does not reference.
    ///
    /// # Errors
    ///
    /// Returns an error when the URL is not under the public URL, the file is
    /// missing or not a regular file, or it resolves outside `dist`.
    pub fn resolve_output_file(
        &self,
        dist: impl AsRef<Path>,
        url: &str,
    ) -> Result<PathBuf, ViewError> {
        let relative = self.output_path_for_url(url)?;
        let root = canonical_output_root(dist.as_ref())?;
        let (file, _) = contained_file(&root, &relative, &format!("output file for `{url}`"))?;
        Ok(file)
    }

    /// Maps a public asset URL or request path to its path relative to the
    /// Trunk output directory, using the same rules as [`Self::validate_output`].
    ///
    /// Servers must use this instead of joining the raw request path onto the
    /// output directory: with a non-root `public_url` such as `/app/`, the URL
    /// `/app/app.js` is the output file `app.js`. The public URL root itself,
    /// with or without its trailing slash (`/app/` or `/app`), is the HTML
    /// entry point named by [`Self::html`].
    ///
    /// # Errors
    ///
    /// Returns an error when the URL is not under `public_url` at a path
    /// boundary, has a query or fragment, or escapes the output directory.
    pub fn output_path_for_url(&self, url: &str) -> Result<PathBuf, ViewError> {
        let root = self.public_url.trim_end_matches('/');
        if url
            .strip_prefix(root)
            .is_some_and(|rest| rest.is_empty() || rest == "/")
            && !url.is_empty()
        {
            return safe_relative_path(&self.html);
        }
        self.local_asset_path(url)
    }

    fn local_asset_path(&self, url: &str) -> Result<PathBuf, ViewError> {
        let relative = url
            .strip_prefix(&self.public_url)
            .and_then(|relative| {
                if self.public_url.ends_with('/') {
                    Some(relative)
                } else {
                    relative.strip_prefix('/')
                }
            })
            .ok_or_else(|| {
                ViewError::msg(format!(
                    "asset URL `{url}` does not use manifest public URL prefix `{}`",
                    self.public_url
                ))
            })?;
        if relative.contains(['?', '#']) {
            return Err(ViewError::msg(format!(
                "asset URL `{url}` contains an unsupported query or fragment"
            )));
        }
        safe_relative_path(relative)
    }
}

fn safe_relative_path(path: &str) -> Result<PathBuf, ViewError> {
    let decoded = percent_decode(path)?;
    if decoded.is_empty() || decoded.contains('\\') {
        return Err(ViewError::msg(format!(
            "invalid relative asset path `{path}`"
        )));
    }
    let path_buf = PathBuf::from(&decoded);
    if path_buf.is_absolute()
        || path_buf
            .components()
            .any(|component| !matches!(component, Component::Normal(_)))
    {
        return Err(ViewError::msg(format!(
            "asset path `{path}` escapes the Trunk output directory"
        )));
    }
    Ok(path_buf)
}

fn percent_decode(path: &str) -> Result<String, ViewError> {
    let bytes = path.as_bytes();
    let mut decoded = Vec::with_capacity(bytes.len());
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index] == b'%' {
            if index + 2 >= bytes.len() {
                return Err(ViewError::msg(format!(
                    "malformed percent escape in asset path `{path}`"
                )));
            }
            let high = hex_digit(bytes[index + 1]);
            let low = hex_digit(bytes[index + 2]);
            let (Some(high), Some(low)) = (high, low) else {
                return Err(ViewError::msg(format!(
                    "malformed percent escape in asset path `{path}`"
                )));
            };
            decoded.push((high << 4) | low);
            index += 3;
        } else {
            decoded.push(bytes[index]);
            index += 1;
        }
    }
    String::from_utf8(decoded)
        .map_err(|_| ViewError::msg(format!("asset path `{path}` is not valid UTF-8")))
}

const fn hex_digit(byte: u8) -> Option<u8> {
    match byte {
        b'0'..=b'9' => Some(byte - b'0'),
        b'a'..=b'f' => Some(byte - b'a' + 10),
        b'A'..=b'F' => Some(byte - b'A' + 10),
        _ => None,
    }
}

fn canonical_output_root(dist: &Path) -> Result<PathBuf, ViewError> {
    dist.canonicalize().map_err(|error| {
        ViewError::msg(format!(
            "failed to resolve Trunk output directory {}: {error}",
            dist.display()
        ))
    })
}

/// Accepts only a root-relative path (`/` or `/app/`) or an absolute `http`/`https`
/// URL, because the value prefixes every URL that callers emit into HTML.
fn validate_public_url(public_url: &str) -> Result<(), ViewError> {
    let lower = public_url.to_ascii_lowercase();
    let after_scheme = lower
        .strip_prefix("https://")
        .or_else(|| lower.strip_prefix("http://"));
    let allowed_form = after_scheme.map_or_else(
        || public_url.starts_with('/') && !public_url.starts_with("//"),
        |rest| !rest.is_empty() && !rest.starts_with('/'),
    );
    let allowed_characters = public_url
        .chars()
        .all(|character| character.is_ascii_graphic() && !"\\\"'<>`".contains(character));
    if allowed_form && allowed_characters {
        Ok(())
    } else {
        Err(ViewError::msg(format!(
            "Trunk asset manifest public URL `{public_url}` must be a root-relative path or an http(s) URL"
        )))
    }
}

/// Resolves `relative` under the canonical output `root`, following symlinks,
/// and rejects files whose real location is outside that root.
fn contained_file(
    root: &Path,
    relative: &Path,
    description: &str,
) -> Result<(PathBuf, std::fs::Metadata), ViewError> {
    let path = root.join(relative);
    let resolved = path
        .canonicalize()
        .map_err(|error| file_error(&path, description, &error))?;
    if !resolved.starts_with(root) {
        return Err(ViewError::msg(format!(
            "{description} {} escapes the Trunk output directory through a symbolic link",
            path.display()
        )));
    }
    let metadata = require_file(&resolved, description)?;
    Ok((resolved, metadata))
}

fn require_file(path: &Path, description: &str) -> Result<std::fs::Metadata, ViewError> {
    match std::fs::metadata(path) {
        Ok(metadata) if metadata.is_file() => Ok(metadata),
        Ok(_) => Err(ViewError::msg(format!(
            "{description} is not a file: {}",
            path.display()
        ))),
        Err(error) => Err(file_error(path, description, &error)),
    }
}

fn file_error(path: &Path, description: &str, error: &std::io::Error) -> ViewError {
    if error.kind() == std::io::ErrorKind::NotFound {
        ViewError::msg(format!("{description} is missing: {}", path.display()))
    } else {
        ViewError::msg(format!(
            "failed to inspect {description} {}: {error}",
            path.display()
        ))
    }
}

fn verify_digest(path: &Path, digest: &str) -> Result<(), ViewError> {
    let (algorithm, expected) = digest
        .split_once('-')
        .ok_or_else(|| ViewError::msg(format!("malformed asset digest `{digest}`")))?;
    let expected = STANDARD
        .decode(expected)
        .map_err(|error| ViewError::msg(format!("malformed asset digest: {error}")))?;
    let contents = std::fs::read(path)
        .map_err(|error| ViewError::msg(format!("failed to read {}: {error}", path.display())))?;
    let actual = match algorithm {
        "sha256" => Sha256::digest(contents).to_vec(),
        "sha384" => Sha384::digest(contents).to_vec(),
        "sha512" => Sha512::digest(contents).to_vec(),
        _ => {
            return Err(ViewError::msg(format!(
                "unsupported asset digest algorithm `{algorithm}`"
            )));
        }
    };
    if actual != expected {
        return Err(ViewError::msg(format!(
            "stale asset {}: content digest check failed",
            path.display()
        )));
    }
    Ok(())
}

